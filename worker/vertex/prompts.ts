/** {名前} を値で置き換える（置き換えた中身の {…} はもう一度は展開しない） */
export function fill(template: string, vars: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? vars[k] : m))
}

